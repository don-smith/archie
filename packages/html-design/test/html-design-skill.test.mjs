import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import { checkArtifact } from "../skills/html-design/scripts/lib/check-artifact.mjs";
import { scaffoldArtifact } from "../skills/html-design/scripts/lib/scaffold-artifact.mjs";

const workspace = path.resolve(import.meta.dirname, "..");
const skill = path.join(workspace, "skills/html-design");
const fixtures = path.join(workspace, "test/fixtures/artifacts");
const repositoryRoot = path.resolve(workspace, "../..");

function run(script, args, cwd) {
  return spawnSync(process.execPath, [script, ...args], { cwd, encoding: "utf8", env: { PATH: process.env.PATH } });
}

function rules(report) {
  return report.diagnostics.map((item) => item.rule);
}

async function filesBelow(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) files.push(...(await filesBelow(path.join(directory, entry.name), relative)));
    else files.push(relative);
  }
  return files.sort();
}

test("the skill is self-contained: no installed dependencies and bundled-package notices present", async () => {
  const files = await filesBelow(skill);
  for (const required of [
    "SKILL.md",
    "LICENSE",
    "THIRD_PARTY_NOTICES.md",
    "assets/theme.js",
    "assets/design-system.css",
    "assets/palettes/moss-paper.css",
    "templates/rail-document.html",
    "templates/review-packet.html",
    "templates/application-shell.html",
    "scripts/check-artifact.mjs",
    "scripts/scaffold-artifact.mjs",
    "scripts/apply-palette.mjs",
    "scripts/refresh-artifact-assets.mjs",
  ]) assert.ok(files.includes(required), required);
  assert.equal(files.some((file) => /(^|\/)(node_modules|package(-lock)?\.json)(\/|$)/.test(file)), false);

  const text = await readFile(path.join(skill, "SKILL.md"), "utf8");
  assert.match(text, /^---\nname: html-design\n/);
  const notices = await readFile(path.join(skill, "THIRD_PARTY_NOTICES.md"), "utf8");
  assert.match(notices, /## parse5 8\.0\.1/);
  assert.match(notices, /## entities 8\.0\.0/);

  const checker = await readFile(path.join(skill, "scripts/lib/check-artifact.mjs"), "utf8");
  assert.match(checker, /^\/\/ Generated by scripts\/bundle-html-design-checker\.mjs/);
  const bareImports = [...checker.matchAll(/^import .* from "([^"]+)";$/gm)].map((match) => match[1]).filter((specifier) => !specifier.startsWith("node:") && !specifier.startsWith("./"));
  assert.deepEqual(bareImports, []);
});

