#!/usr/bin/env node
// Generates the dependency-free html-design artifact checker. The deployed skill
// must run without node_modules, so parse5 is inlined while the checker's sibling
// palette-assets module stays a relative import resolved inside the skill.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const root = path.resolve(import.meta.dirname, "..");
const source = path.join(root, "packages/html-design/src/check-artifact.mjs");
const output = path.join(root, "packages/html-design/skills/html-design/scripts/lib/check-artifact.mjs");
const banner = "// Generated by scripts/bundle-html-design-checker.mjs from packages/html-design/src/check-artifact.mjs. Do not edit.\n// Bundles parse5 and entities; see ../../THIRD_PARTY_NOTICES.md.";

const keepSiblingModules = {
  name: "keep-sibling-modules",
  setup(pluginBuild) {
    pluginBuild.onResolve({ filter: /^\.\/[^/]+\.mjs$/ }, (args) => ({ path: args.path, external: true }));
  },
};

const result = await build({
  entryPoints: [source],
  absWorkingDir: root,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node24",
  legalComments: "none",
  banner: { js: banner },
  plugins: [keepSiblingModules],
  write: false,
});
const generated = result.outputFiles[0].text;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated) {
    console.error(`${path.relative(root, output)} is stale; run node scripts/bundle-html-design-checker.mjs`);
    process.exitCode = 1;
  } else {
    console.log("html-design artifact checker bundle verified.");
  }
} else {
  writeFileSync(output, generated);
  console.log("html-design artifact checker bundle generated.");
}
